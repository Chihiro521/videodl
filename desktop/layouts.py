"""Compact monochrome shell and the home-to-results download page."""

from pathlib import Path

from PySide6.QtCore import QSize, Qt, QTimer
from PySide6.QtGui import QKeySequence, QShortcut
from PySide6.QtWidgets import (QCheckBox, QComboBox, QFrame, QHBoxLayout, QHeaderView, QLineEdit,
    QProgressBar, QSizePolicy, QSpacerItem, QStackedWidget, QToolButton, QVBoxLayout, QWidget)

from . import __version__
from .theme import set_symbol
from .widgets import LinkInput, SegmentedControl, button, label, tool_button


def build_shell(window):
    root = QWidget()
    root.setObjectName("root")
    outer = QHBoxLayout(root)
    outer.setContentsMargins(0, 0, 0, 0)
    outer.setSpacing(0)
    sidebar = QFrame()
    sidebar.setObjectName("sidebar")
    sidebar.setFixedWidth(84)
    side = QVBoxLayout(sidebar)
    side.setContentsMargins(6, 13, 6, 13)
    side.setSpacing(8)
    mark = label("VD", "sidebarBrand")
    mark.setAlignment(Qt.AlignmentFlag.AlignCenter)
    mark.setFixedHeight(40)
    mark.setToolTip("VideoDL Desktop")
    side.addWidget(mark)
    side.addSpacing(7)
    window.nav = []
    for index, (text, symbol) in enumerate((("下载", "download"), ("队列", "queue"),
                                           ("设置", "settings"), ("关于", "update"))):
        if index == 2:
            side.addStretch()
        control = QToolButton()
        control.setObjectName("nav")
        control.setText(text)
        control.setAccessibleName(("链接下载", "下载队列", "设置", "关于与更新")[index])
        control.setToolButtonStyle(Qt.ToolButtonStyle.ToolButtonTextUnderIcon)
        control.setIconSize(QSize(21, 21))
        control.setCheckable(True)
        control.setMinimumHeight(63)
        control.setMinimumWidth(68)
        control.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Fixed)
        control.setCursor(Qt.CursorShape.PointingHandCursor)
        set_symbol(control, symbol)
        control.clicked.connect(lambda checked=False, current=index: window.navigate(current))
        window.nav.append(control)
        side.addWidget(control)
    version = label(__version__, "muted")
    version.setAlignment(Qt.AlignmentFlag.AlignCenter)
    side.addWidget(version)
    outer.addWidget(sidebar)
    right = QVBoxLayout()
    right.setContentsMargins(0, 0, 0, 0)
    right.setSpacing(0)
    window.pages = QStackedWidget()
    for make in (window._new_page, window._queue_page, window._settings_page, window._updates_page):
        window.pages.addWidget(make())
    right.addWidget(window.pages, 1)
    window.destination_bar = QFrame()
    window.destination_bar.setObjectName("destinationBar")
    save = QHBoxLayout(window.destination_bar)
    save.setContentsMargins(24, 12, 24, 12)
    save.setSpacing(9)
    save.addWidget(label("保存到", "muted"))
    window.destination = QLineEdit(window.settings.get("output", str(Path.home() / "Downloads" / "VideoDL")))
    window.destination.setAccessibleName("保存路径")
    window.destination.editingFinished.connect(window.persist)
    save.addWidget(window.destination, 1)
    save.addWidget(button("更改", window.choose_directory))
    save.addWidget(tool_button("folder", "打开保存文件夹", lambda: window.open_folder(window.destination.text())))
    save.addWidget(label("保存方式", "muted"))
    window.save_mode = QComboBox()
    window.save_mode.setAccessibleName("保存方式")
    window.save_mode.addItem("直接保存文件", "flat")
    window.save_mode.addItem("按作品分文件夹", "by_work")
    window.save_mode.addItem("按类型分文件夹", "by_type")
    window.save_mode.setCurrentIndex(max(0, window.save_mode.findData(window.settings.get("save_mode", "flat"))))
    window.save_mode.setToolTip("选择新下载任务的保存方式；已加入队列的任务继续使用原方式")
    window.save_mode.currentIndexChanged.connect(window.schedule_settings_save)
    save.addWidget(window.save_mode)
    right.addWidget(window.destination_bar)
    outer.addLayout(right, 1)
    window.setCentralWidget(root)
    window.navigate(0)
    window.statusBar().setSizeGripEnabled(False)
    window.statusBar().showMessage("准备就绪")


def build_download_page(window):
    page, layout = window.page("")
    layout.setContentsMargins(26, 25, 26, 17)
    layout.setSpacing(14)
    window.download_layout = layout
    window.home_top_space = QSpacerItem(0, 0, QSizePolicy.Policy.Minimum, QSizePolicy.Policy.Expanding)
    layout.addItem(window.home_top_space)
    window.home_intro = QWidget()
    intro = QVBoxLayout(window.home_intro)
    intro.setContentsMargins(0, 0, 0, 13)
    intro.setSpacing(8)
    window.home_mark = label("")
    window.home_mark.setAlignment(Qt.AlignmentFlag.AlignCenter)
    window.home_mark.setMinimumHeight(65)
    intro.addWidget(window.home_mark)
    name = label("VideoDL", "brand")
    name.setAlignment(Qt.AlignmentFlag.AlignCenter)
    intro.addWidget(name)
    layout.addWidget(window.home_intro, 0, Qt.AlignmentFlag.AlignHCenter)
    window.input_frame = QFrame()
    window.input_frame.setObjectName("inputPanel")
    window.input_frame.setMaximumWidth(720)
    window.input_frame.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Maximum)
    top = QVBoxLayout(window.input_frame)
    top.setContentsMargins(0, 0, 0, 0)
    top.setSpacing(8)
    link_box = QFrame()
    link_box.setObjectName("linkBox")
    entry = QHBoxLayout(link_box)
    entry.setContentsMargins(2, 3, 5, 3)
    entry.setSpacing(0)
    window.links = LinkInput()
    window.links.setObjectName("linkInput")
    window.links.setAccessibleName("视频分享链接，支持单行、多行和分享文本")
    window.links.setPlaceholderText("粘贴一行、多行链接或分享文本")
    window.links.textChanged.connect(window.update_link_count)
    entry.addWidget(window.links, 1)
    window.parse_button = button("提取链接", window.start_preview, "primary")
    window.parse_button.setFixedWidth(140)
    window.parse_button.setMinimumHeight(38)
    entry.addWidget(window.parse_button)
    link_box.setFixedHeight(window.links.height() + 8)
    window.links.heightChanged.connect(lambda height: link_box.setFixedHeight(height + 8))
    top.addWidget(link_box)
    actions = QHBoxLayout()
    actions.setContentsMargins(0, 0, 0, 0)
    actions.setSpacing(8)
    window.link_count = label("支持单行、多行链接或分享文本 · 最多 200 条", "muted")
    window.link_count.setWordWrap(False)
    window.link_count.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    actions.addWidget(window.link_count, 1)
    window.auto_download = QCheckBox("提取后自动下载")
    window.auto_download.setChecked(bool(window.settings.get("auto_download", False)))
    window.auto_download.toggled.connect(window.schedule_settings_save)
    actions.addWidget(window.auto_download)
    actions.addWidget(button("粘贴", window.paste, "small", "paste"))
    actions.addWidget(tool_button("close", "清空输入框", window.links.clear))
    window.stop_extract = button("停止提取", window.cancel_extraction, "small")
    window.stop_extract.hide()
    actions.addWidget(window.stop_extract)
    top.addLayout(actions)
    window.extract_progress = QProgressBar()
    window.extract_progress.setTextVisible(False)
    window.extract_progress.hide()
    top.addWidget(window.extract_progress)
    layout.addWidget(window.input_frame, 0, Qt.AlignmentFlag.AlignHCenter)
    shortcut = QShortcut(QKeySequence("Ctrl+Return"), window.links)
    shortcut.setContext(Qt.ShortcutContext.WidgetWithChildrenShortcut)
    shortcut.activated.connect(window.start_preview)
    window.results_panel = QWidget()
    window.results_panel.setObjectName("resultsPanel")
    area = QVBoxLayout(window.results_panel)
    area.setContentsMargins(0, 8, 0, 0)
    area.setSpacing(12)
    toolbar = QHBoxLayout()
    toolbar.setSpacing(12)
    window.type_filter = SegmentedControl()
    window.type_filter.setAccessibleName("筛选类型")
    for text, value in (("全部", ""), ("视频", "video"), ("音频", "audio"), ("封面", "cover")):
        window.type_filter.addItem(text, value)
    window.type_filter.currentIndexChanged.connect(window.render_results)
    toolbar.addWidget(window.type_filter)
    window.result_summary = label("暂无提取结果", "muted")
    window.result_summary.setWordWrap(False)
    window.result_summary.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    toolbar.addWidget(window.result_summary, 1)
    window.result_search = QLineEdit()
    window.result_search.setAccessibleName("搜索标题")
    window.result_search.setPlaceholderText("搜索标题")
    window.result_search.setClearButtonEnabled(True)
    window.result_search.setFixedWidth(156)
    window.result_search_timer = QTimer(window)
    window.result_search_timer.setSingleShot(True)
    window.result_search_timer.setInterval(150)
    window.result_search_timer.timeout.connect(window.render_results)
    window.result_search.textChanged.connect(lambda: window.result_search_timer.start())
    toolbar.addWidget(window.result_search)
    area.addLayout(toolbar)
    info = QHBoxLayout()
    info.setSpacing(10)
    window.select_all = QCheckBox("全选")
    window.select_all.setTristate(True)
    window.select_all.clicked.connect(window.select_visible)
    info.addWidget(window.select_all)
    window.message = label("按需选择视频、音频和封面。", "muted")
    window.message.setWordWrap(False)
    window.message.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    info.addWidget(window.message, 1)
    window.download_selected_button = button("下载选中", window.download_selected)
    info.addWidget(window.download_selected_button)
    window.download_all_button = button("全部下载", window.download_visible, "primary")
    info.addWidget(window.download_all_button)
    info.addWidget(tool_button("clear", "清空提取结果，保留下载任务与文件", window.clear_results))
    area.addLayout(info)
    errors = QHBoxLayout()
    window.retry_extract_button = button("重试失败链接", window.retry_extraction, "small")
    window.extract_errors_button = button("查看详情", window.show_extraction_errors, "small")
    for control in (window.retry_extract_button, window.extract_errors_button):
        control.hide()
        errors.addWidget(control)
    errors.addStretch()
    area.addLayout(errors)
    window.result_stack = QStackedWidget()
    empty = QFrame()
    empty.setObjectName("emptyState")
    empty_box = QVBoxLayout(empty)
    empty_box.addStretch()
    window.empty_title = label("暂无结果", "emptyTitle")
    window.empty_detail = label("", "muted")
    for control in (window.empty_title, window.empty_detail):
        control.setAlignment(Qt.AlignmentFlag.AlignCenter)
        empty_box.addWidget(control)
    empty_box.addStretch()
    window.result_stack.addWidget(empty)
    window.results_table = window.make_table(["", "标题", "类型 / 画质", "状态", "操作"])
    window.results_table.setColumnWidth(0, 34)
    window.results_table.horizontalHeader().setSectionResizeMode(1, QHeaderView.ResizeMode.Stretch)
    for column, width in ((2, 210), (3, 102), (4, 80)):
        window.results_table.setColumnWidth(column, width)
    window.result_stack.addWidget(window.results_table)
    area.addWidget(window.result_stack, 1)
    layout.addWidget(window.results_panel, 1)
    window.home_bottom_space = QSpacerItem(0, 0, QSizePolicy.Policy.Minimum, QSizePolicy.Policy.Expanding)
    layout.addItem(window.home_bottom_space)
    return page
