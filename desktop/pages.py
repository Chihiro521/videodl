"""Page layouts for the single-screen extraction-to-download workflow."""

from pathlib import Path

from PySide6.QtCore import Qt, QUrl
from PySide6.QtGui import QDesktopServices, QKeySequence, QShortcut
from PySide6.QtWidgets import (QCheckBox, QComboBox, QFormLayout, QFrame, QHBoxLayout,
    QHeaderView, QLineEdit, QMenu, QPlainTextEdit, QSizePolicy, QSpinBox, QStackedWidget,
    QTableWidget, QToolButton, QVBoxLayout, QWidget)

from . import REPOSITORY, __version__
from .results import KINDS
from .theme import icon
from .updates import build_info
from .widgets import button, card, label, tool_button


class WorkbenchPages:
    def _build(self):
        root = QWidget()
        root.setObjectName("root")
        outer = QHBoxLayout(root)
        outer.setContentsMargins(0, 0, 0, 0)
        outer.setSpacing(0)
        sidebar = QFrame()
        sidebar.setObjectName("sidebar")
        sidebar.setFixedWidth(202)
        side = QVBoxLayout(sidebar)
        side.setContentsMargins(14, 23, 14, 18)
        side.setSpacing(8)
        brand = QHBoxLayout()
        mark = label("")
        mark.setPixmap(icon("download", "#2563eb", 25).pixmap(25, 25))
        brand.addWidget(mark)
        brand.addWidget(label("VideoDL", "brand"))
        brand.addStretch()
        side.addLayout(brand)
        side.addSpacing(19)
        self.nav = []
        for index, (text, symbol) in enumerate((("链接下载", "download"), ("下载队列", "queue"),
                                               ("设置", "settings"), ("关于与更新", "update"))):
            if index == 2:
                side.addStretch()
            nav = button(text, lambda _, i=index: self.navigate(i), "nav", symbol)
            nav.setCheckable(True)
            nav.setMinimumHeight(43)
            self.nav.append(nav)
            side.addWidget(nav)
        side.addSpacing(12)
        side.addWidget(label(f"VideoDL Desktop  {__version__}", "muted"))
        outer.addWidget(sidebar)
        right = QVBoxLayout()
        right.setContentsMargins(0, 0, 0, 0)
        right.setSpacing(0)
        self.pages = QStackedWidget()
        for make in (self._new_page, self._queue_page, self._settings_page, self._updates_page):
            self.pages.addWidget(make())
        right.addWidget(self.pages, 1)
        footer = QFrame()
        footer.setObjectName("destinationBar")
        save_row = QHBoxLayout(footer)
        save_row.setContentsMargins(20, 11, 20, 11)
        save_row.setSpacing(9)
        save_row.addWidget(label("保存路径", "muted"))
        self.destination = QLineEdit(self.settings.get("output", str(Path.home() / "Downloads" / "VideoDL")))
        self.destination.setAccessibleName("保存路径")
        self.destination.editingFinished.connect(self.persist)
        save_row.addWidget(self.destination, 1)
        save_row.addWidget(button("更改文件夹", self.choose_directory))
        save_row.addWidget(tool_button("folder", "打开保存文件夹", lambda: self.open_folder(self.destination.text())))
        right.addWidget(footer)
        outer.addLayout(right, 1)
        self.setCentralWidget(root)
        self.navigate(0)
        self.statusBar().showMessage("准备就绪")

    def page(self, title, subtitle=""):
        content = QWidget()
        content.setObjectName("page")
        layout = QVBoxLayout(content)
        layout.setContentsMargins(25, 22, 25, 20)
        layout.setSpacing(16)
        if title:
            layout.addWidget(label(title, "title"))
        if subtitle:
            layout.addWidget(label(subtitle, "muted"))
        return content, layout

